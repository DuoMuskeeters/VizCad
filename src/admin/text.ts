const TEXTS: Partial<Record<Locale, AdminText>> = { en, tr }

export const adminText = (locale: Locale): AdminText => TEXTS[locale] ?? en

export const useAdminText = () => {
  const { locale } = useI18n()
  return { text: adminText(locale), locale }
}
